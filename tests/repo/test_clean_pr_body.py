from pathlib import Path

import pytest

from tools.clean_pr_body import clean, main

OURS = "Designed and reviewed by @someone, built with [Claude Code](https://claude.com/claude-code)"
BODY = f"## What changes\n\nText.\n\n---\n\n{OURS}\n"
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
SESSION = "https://claude.ai/code/session_01AbCdEfGh"


def test_removes_the_appended_footer_and_its_separator() -> None:
    assert clean(f"{BODY}\n\n---\n{FOOTER}\n") == BODY


def test_removes_the_footer_that_carries_a_session_link() -> None:
    footer = f"_Generated by [Claude Code]({SESSION})_"
    assert clean(f"{BODY}\n\n---\n{footer}\n") == BODY


def test_removes_the_default_generated_with_line() -> None:
    line = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
    assert clean(f"## What changes\n\nText.\n\n{line}\n") == "## What changes\n\nText.\n"


def test_removes_a_bare_session_link_line() -> None:
    assert clean(f"{BODY}\n{SESSION}\n") == BODY


def test_keeps_our_own_attribution_line_and_its_separator() -> None:
    assert clean(BODY) == BODY


def test_keeps_separators_that_do_not_precede_a_removed_line() -> None:
    body = "Intro\n\n---\n\nMore text\n"
    assert clean(f"{body}\n---\n{FOOTER}\n") == body


def test_keeps_a_session_link_that_is_part_of_a_sentence() -> None:
    body = f"See {SESSION} for the discussion.\n"
    assert clean(body) == body


def test_an_empty_description_stays_empty() -> None:
    assert clean("") == ""


def test_main_rewrites_the_file_and_reports_whether_it_changed(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    dirty = tmp_path / "dirty.md"
    dirty.write_text(f"{BODY}\n\n---\n{FOOTER}\n", encoding="utf-8")
    assert main([str(dirty)]) == 0
    assert dirty.read_text(encoding="utf-8") == BODY
    assert capsys.readouterr().out.strip() == "changed=true"

    assert main([str(dirty)]) == 0
    assert dirty.read_text(encoding="utf-8") == BODY
    assert capsys.readouterr().out.strip() == "changed=false"


def test_line_endings_and_a_missing_final_newline_do_not_count_as_a_change(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    path = tmp_path / "body.md"
    path.write_bytes(BODY.replace("\n", "\r\n").rstrip().encode("utf-8"))
    assert main([str(path)]) == 0
    assert capsys.readouterr().out.strip() == "changed=false"
