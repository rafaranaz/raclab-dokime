"""Pull request description cleaner: keeps a single, chosen attribution line.

Tooling that opens or edits pull requests may append its own attribution footer or a link to the
session that produced the change. The repository credits its authors with one line from the pull
request template, so this removes the appended ones and nothing else.
"""

import argparse
import re
from pathlib import Path

ATTRIBUTION_LINES = (
    re.compile(r"^_Generated by \[Claude Code\]\([^)]*\)_$"),
    re.compile(r"^(?:\N{ROBOT FACE}\s*)?Generated with \[Claude Code\]\([^)]*\)$"),
)
SESSION_LINK = re.compile(r"^https://claude\.ai/code/session_\S+$")
SEPARATOR = re.compile(r"^-{3,}$")


def _is_attribution(line: str) -> bool:
    return any(pattern.match(line.strip()) for pattern in ATTRIBUTION_LINES)


def _drop_separator_above(lines: list[str]) -> None:
    """Remove the separator that introduces an attribution line, with the blank lines between."""
    index = len(lines) - 1
    while index >= 0 and not lines[index].strip():
        index -= 1
    if index >= 0 and SEPARATOR.match(lines[index].strip()):
        del lines[index:]


def clean(body: str) -> str:
    """Return `body` without appended attribution lines, their separators and session links."""
    kept: list[str] = []
    for line in body.splitlines():
        if _is_attribution(line):
            _drop_separator_above(kept)
        elif not SESSION_LINK.match(line.strip()):
            kept.append(line)
    while kept and not kept[-1].strip():
        kept.pop()
    return "\n".join(kept) + "\n" if kept else ""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", type=Path, help="file holding the description; rewritten in place")
    args = parser.parse_args(argv)
    original = args.path.read_bytes().decode("utf-8")
    cleaned = clean(original)
    args.path.write_text(cleaned, encoding="utf-8")
    changed = cleaned.rstrip() != original.replace("\r\n", "\n").rstrip()
    print(f"changed={'true' if changed else 'false'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
